// Shared helpers for the deep-wiki scripts. Zero dependencies.
import fs from 'node:fs'
import path from 'node:path'

export const MARKER = '<!-- generated by deep-wiki -->'

/** Onboarding pages in reading order, hub first. */
export const ONBOARDING_ORDER = [
  'index.md',
  'contributor-guide.md',
  'staff-engineer-guide.md',
  'executive-guide.md',
  'product-manager-guide.md',
]

// Not part of the site. Skipped at the wiki root only: a section may own a folder with one of these names.
const ROOT_SKIP_DIRS = new Set(['node_modules', 'dist', 'scripts', 'public'])
const SKIP_FILES = new Set(['AGENTS.md', 'CLAUDE.md', 'README.md'])

export const posix = (p) => p.split(path.sep).join('/')

/** Read a UTF-8 text file without its byte-order mark. */
export function readText(file) {
  return fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '')
}

/** Every wiki page under `wikiDir`, as sorted paths relative to it (forward slashes). */
export function listPages(wikiDir) {
  const out = []
  const visit = (dir) => {
    for (const e of fs.readdirSync(path.join(wikiDir, dir), { withFileTypes: true })) {
      const rel = dir ? `${dir}/${e.name}` : e.name
      if (e.isDirectory()) {
        if (!e.name.startsWith('.') && !(dir === '' && ROOT_SKIP_DIRS.has(e.name))) visit(rel)
      } else if (e.name.endsWith('.md') && !SKIP_FILES.has(e.name)) {
        out.push(rel)
      }
    }
  }
  visit('')
  return out.sort()
}

function unquote(value) {
  const q = value[0]
  if (value.length >= 2 && (q === '"' || q === "'") && value.endsWith(q)) {
    const inner = value.slice(1, -1)
    return q === '"' ? inner.replace(/\\(["\\])/g, '$1') : inner.replace(/''/g, "'")
  }
  return value
}

/** Why a raw `title`/`description` value would not survive a real YAML parser, or null when it is fine. */
function yamlProblem(raw) {
  if (raw === '') return 'is empty'
  if (/^[>|][+-]?\d*\s*$/.test(raw)) return 'is a block scalar; write the value on one line'
  const q = raw[0]
  if (q === '"' || q === "'") {
    return raw.length >= 2 && raw.endsWith(q) ? null : 'has an unbalanced quote'
  }
  if (/: |:$| #/.test(raw) || /^[[\]{}>|*&!%@`#,]/.test(raw) || /^[-?:] /.test(raw)) {
    return 'must be wrapped in double quotes (it contains YAML syntax)'
  }
  return null
}

/**
 * Flat `key: value` frontmatter. `data` is null when the file has no frontmatter block.
 * `issues` lists `title`/`description` values a YAML parser would reject or misread.
 */
export function parseFrontmatter(text) {
  const m = text.replace(/^\uFEFF/, '').match(/^---\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/)
  if (!m) return { data: null, lineCount: 0, issues: [] }
  const data = {}
  const issues = []
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_][\w-]*):(?:\s+(.*))?$/)
    if (!kv) continue
    const raw = (kv[2] ?? '').trim()
    const problem = kv[1] === 'title' || kv[1] === 'description' ? yamlProblem(raw) : null
    if (problem) issues.push({ key: kv[1], problem })
    data[kv[1]] = problem && !/quote|YAML/.test(problem) ? '' : unquote(raw)
  }
  return { data, lineCount: m[0].split('\n').length - 1, issues }
}

/** A YAML double-quoted scalar, safe for any title or description. */
export const yamlString = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`

/** Parsed `catalogue.json`, or null when the file does not exist. Throws on invalid JSON. */
export function loadCatalogue(wikiDir) {
  const file = path.join(wikiDir, 'catalogue.json')
  if (!fs.existsSync(file)) return null
  return JSON.parse(readText(file))
}

/**
 * Run state from `<wiki>/.deep-wiki.json`: `{ depth, host, repoUrl, branch, base, wikiDir }`.
 * Returns `{}` when the file is missing or unreadable.
 */
export function loadState(wikiDir) {
  try {
    const state = JSON.parse(readText(path.join(wikiDir, '.deep-wiki.json')))
    return state && typeof state === 'object' && !Array.isArray(state) ? state : {}
  } catch {
    return {}
  }
}

/** Section folder relative to the wiki root; tolerates a nested `dir` given without its parent. */
export function resolveDir(node, parentDir) {
  const dir = String(node.dir).replace(/\\/g, '/').replace(/^\.?\/+|\/+$/g, '')
  return parentDir && !dir.startsWith(`${parentDir}/`) ? `${parentDir}/${dir}` : dir
}

/**
 * Depth-first walk over catalogue nodes. `visit(node, { depth, parent, dir, parentDir })`;
 * `dir` is set for section nodes. Entries that are not objects are skipped.
 */
export function walkCatalogue(items, visit, depth = 1, parent = null, parentDir = '') {
  for (const node of Array.isArray(items) ? items : []) {
    if (!node || typeof node !== 'object' || Array.isArray(node)) continue
    const dir = typeof node.dir === 'string' ? resolveDir(node, parentDir) : null
    visit(node, { depth, parent, dir, parentDir })
    walkCatalogue(node.children, visit, depth + 1, node, dir ?? parentDir)
  }
}
