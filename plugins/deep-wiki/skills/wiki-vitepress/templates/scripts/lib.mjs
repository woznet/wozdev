// Shared helpers for the deep-wiki scripts. Zero dependencies.
import fs from 'node:fs'
import path from 'node:path'

export const MARKER = '<!-- generated by deep-wiki -->'

const SKIP_DIRS = new Set(['node_modules', 'dist', 'scripts', 'public'])
const SKIP_FILES = new Set(['AGENTS.md', 'CLAUDE.md', 'README.md'])

export const posix = (p) => p.split(path.sep).join('/')

/** Every wiki page under `wikiDir`, as sorted paths relative to it (forward slashes). */
export function listPages(wikiDir) {
  const out = []
  const visit = (dir) => {
    for (const e of fs.readdirSync(path.join(wikiDir, dir), { withFileTypes: true })) {
      const rel = dir ? `${dir}/${e.name}` : e.name
      if (e.isDirectory()) {
        if (!e.name.startsWith('.') && !SKIP_DIRS.has(e.name)) visit(rel)
      } else if (e.name.endsWith('.md') && !SKIP_FILES.has(e.name)) {
        out.push(rel)
      }
    }
  }
  visit('')
  return out.sort()
}

function unquote(value) {
  const q = value[0]
  if (value.length >= 2 && (q === '"' || q === "'") && value.endsWith(q)) {
    const inner = value.slice(1, -1)
    return q === '"' ? inner.replace(/\\(["\\])/g, '$1') : inner.replace(/''/g, "'")
  }
  return value
}

/** Flat `key: value` frontmatter. `data` is null when the file has no frontmatter block. */
export function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/)
  if (!m) return { data: null, lineCount: 0 }
  const data = {}
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/)
    if (kv) data[kv[1]] = unquote(kv[2].trim())
  }
  return { data, lineCount: m[0].split('\n').length - 1 }
}

/** A YAML double-quoted scalar, safe for any title or description. */
export const yamlString = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`

/** Parsed `catalogue.json`, or null when the file does not exist. Throws on invalid JSON. */
export function loadCatalogue(wikiDir) {
  const file = path.join(wikiDir, 'catalogue.json')
  if (!fs.existsSync(file)) return null
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

/** Section folder relative to the wiki root; tolerates a nested `dir` given without its parent. */
export function resolveDir(node, parentDir) {
  const dir = String(node.dir).replace(/\\/g, '/').replace(/^\.?\/+|\/+$/g, '')
  return parentDir && !dir.startsWith(`${parentDir}/`) ? `${parentDir}/${dir}` : dir
}

/** Depth-first walk. `visit(node, { depth, parent, dir })`; `dir` is set for section nodes. */
export function walkCatalogue(items, visit, depth = 1, parent = null, parentDir = '') {
  for (const node of Array.isArray(items) ? items : []) {
    const dir = typeof node.dir === 'string' ? resolveDir(node, parentDir) : null
    visit(node, { depth, parent, dir })
    walkCatalogue(node.children, visit, depth + 1, node, dir ?? parentDir)
  }
}
